    private String askQuestion(String question) {
        String cached = cache.get(question.toLowerCase());
        if (cached != null) return cached;

        try (Connection conn = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS)) {
            PreparedStatement ps = conn.prepareStatement(
                "SELECT answer, category, confidence FROM knowledge_base WHERE question LIKE ? OR answer LIKE ? ORDER BY confidence DESC LIMIT 1");
            ps.setString(1, "%" + question + "%"); ps.setString(2, "%" + question + "%");
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {
                String answer = "FIDUCIARY|[" + rs.getString("category") + "] " + rs.getString("answer");
                cache.put(question.toLowerCase(), answer);
                storeSession(question, answer);
                return answer;
            }
        } catch (Exception e) { return "ERROR|" + e.getMessage(); }

        String ai = StrernaryConnector.ask("FIDUCIARY trust wealth yield " + question);
        if (ai != null) { String a = "FIDUCIARY_AI|" + ai; storeSession(question, a); return a; }
        return "FIDUCIARY|Query not matched. Try: fiduciary duty, yield, architecture, trust, remedy, transfer, advantage, polyblend.";
    }

    private String queryYield(String model) {
        try (Connection conn = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS)) {
            PreparedStatement ps = conn.prepareStatement(
                "SELECT model_name, base_yield, turn_frequency, risk_factor, polyblend_weight, assumption_basis FROM yield_models WHERE model_name LIKE ? OR description LIKE ? OR assumption_basis LIKE ?");
            ps.setString(1, "%" + model + "%"); ps.setString(2, "%" + model + "%"); ps.setString(3, "%" + model + "%");
            ResultSet rs = ps.executeQuery();
            StringBuilder sb = new StringBuilder("YIELD|");
            while (rs.next()) {
                sb.append(rs.getString("model_name")).append(": ")
                  .append(rs.getBigDecimal("base_yield")).append("% (turn: ")
                  .append(rs.getString("turn_frequency")).append(", risk: ")
                  .append(rs.getBigDecimal("risk_factor")).append(", weight: ")
                  .append(rs.getBigDecimal("polyblend_weight")).append(") — ")
                  .append(rs.getString("assumption_basis")).append("|");
            }
            return sb.length() > 6 ? sb.toString() : "YIELD|No models found for: " + model;
        } catch (Exception e) { return "ERROR|" + e.getMessage(); }
    }

