    private String computePolyblend() {
        try (Connection conn = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS)) {
            ResultSet rs = conn.createStatement().executeQuery(
                "SELECT model_name, base_yield, polyblend_weight FROM yield_models");
            double weightedYield = 0.0; double totalWeight = 0.0;
            StringBuilder components = new StringBuilder();
            while (rs.next()) {
                double yield = rs.getDouble("base_yield");
                double weight = rs.getDouble("polyblend_weight");
                weightedYield += yield * weight;
                totalWeight += weight;
                components.append(rs.getString("model_name")).append("=")
                  .append(String.format("%.2f%%×%.3f", yield, weight)).append(", ");
            }
            double blended = totalWeight > 0 ? weightedYield / totalWeight : 0;
            return String.format("POLYBLEND|Composite yield assumption: %.4f%% | Components: %s| Total weight: %.3f",
                blended, components, totalWeight);
        } catch (Exception e) { return "ERROR|" + e.getMessage(); }
    }

