function cd1Send(){
    var s=document.getElementById("cd1-action"),t=document.getElementById("cd1-textarea");
    var portEl=document.getElementById("cd1-port"),roleEl=document.getElementById("cd1-role");
    if(!s||!t)return;
    var action=s.value,ts=new Date().toLocaleTimeString();
    var port=portEl?portEl.value:"19000",role=roleEl?roleEl.value:"guest";
    var msg="";
    switch(action){
        case"setport":msg="["+ts+"] SET PORT|"+port+" — Routed\n";break;
        case"unsetport":msg="["+ts+"] UNSET PORT|"+port+" — Disconnected\n";break;
        case"saveconfig":localStorage.setItem("nwe-port",port);localStorage.setItem("nwe-role",role);msg="["+ts+"] SAVE|port="+port+"|role="+role+" — Saved\n";break;
