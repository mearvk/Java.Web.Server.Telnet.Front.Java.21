#!/bin/bash
# ============================================================================
# NWE Website Generator — Skeleton Builder
# Generates a complete BMA-style JSP servlet website from a subject definition.
#
# Creates: JSP pages, CSS, JS, CD1 connectors, status page with port indicators,
# deploy scripts, db.properties template, and SQL schema from nouns/objects.
#
# Usage:
#   bash scripts/generate-website.sh <module-name> <config-file>
#   bash scripts/generate-website.sh MyModule scripts/website-subjects/mymodule.xml
#
# The config file (XML) defines:
#   - Module name, color, ports, database
#   - Content headers (page names)
#   - Nouns/objects (become DB tables and JSP data pages)
#   - Port assignments per page
#
# Lookup scripts (run before this to discover nouns):
#   bash scripts/discover-subjects.sh <source-dir>  → generates subject XML
#
# Author: Max Rupplin — MEARVK LLC
# DIGTIK: SecurityHeadersFilter, PreparedStatement, 44px tap targets, CD1
# ============================================================================



SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"

# ─── Argument Parsing ───
MODULE_NAME="${1:-NewModule}"
CONFIG_FILE="${2:-}"

if [ -z "$CONFIG_FILE" ] || [ ! -f "$CONFIG_FILE" ]; then
    echo "═══════════════════════════════════════════════════════════════"
    echo " NWE Website Generator"
    echo "═══════════════════════════════════════════════════════════════"
    echo ""
    echo " Usage: bash scripts/generate-website.sh <module-name> <config.xml>"
    echo ""
    echo " Config XML format:"
    echo '   <website-config>'
    echo '     <module name="MyModule" color="#3b82f6" database="nwe_mymodule"/>'
    echo '     <ports start="19000" end="19007"/>'
    echo '     <pages>'
    echo '       <page name="Overview" file="index" default="true"/>'
    echo '       <page name="Data" file="data" port="19000"/>'
    echo '       <page name="Reports" file="reports" port="19001"/>'
    echo '       <page name="Status" file="status"/>'
    echo '     </pages>'
    echo '     <nouns>'
    echo '       <noun name="records" table="module_records" columns="id,title,category,value,created_at"/>'
    echo '       <noun name="sources" table="module_sources" columns="id,name,url,type,active"/>'
    echo '     </nouns>'
    echo '   </website-config>'
    echo ""
    echo " Generate a config from existing data:"
    echo "   bash scripts/discover-subjects.sh <source-dir>"
    echo ""
    exit 1
fi

# ─── Parse Config (simple grep-based, no external XML tools needed) ───
MODULE_COLOR=$(grep -oP 'color="\K[^"]+' "$CONFIG_FILE" | head -1)
MODULE_DB=$(grep -oP 'database="\K[^"]+' "$CONFIG_FILE" | head -1)
PORT_START=$(grep -oP 'start="\K[^"]+' "$CONFIG_FILE" | head -1)
PORT_END=$(grep -oP 'end="\K[^"]+' "$CONFIG_FILE" | head -1)
MODULE_COLOR="${MODULE_COLOR:-#3b82f6}"
MODULE_DB="${MODULE_DB:-nwe_${MODULE_NAME,,}}"
PORT_START="${PORT_START:-19000}"
PORT_END="${PORT_END:-19007}"

# Extract pages
PAGES=()
PAGE_FILES=()
PAGE_PORTS=()
while IFS= read -r line; do
    pname=$(echo "$line" | grep -oP 'name="\K[^"]+')
    pfile=$(echo "$line" | grep -oP 'file="\K[^"]+')
    pport=$(echo "$line" | grep -oP 'port="\K[^"]+')
    [ -n "$pname" ] && PAGES+=("$pname") && PAGE_FILES+=("$pfile") && PAGE_PORTS+=("${pport:-0}")
done < <(grep '<page ' "$CONFIG_FILE")

# Extract nouns
NOUNS=()
NOUN_TABLES=()
NOUN_COLUMNS=()
while IFS= read -r line; do
    nname=$(echo "$line" | grep -oP 'name="\K[^"]+')
    ntable=$(echo "$line" | grep -oP 'table="\K[^"]+')
    ncols=$(echo "$line" | grep -oP 'columns="\K[^"]+')
    [ -n "$nname" ] && NOUNS+=("$nname") && NOUN_TABLES+=("$ntable") && NOUN_COLUMNS+=("$ncols")
done < <(grep '<noun ' "$CONFIG_FILE")

# ─── Output Directories ───
OUT_DIR="$PROJECT_ROOT/generated/$MODULE_NAME"
WEBAPP_DIR="$OUT_DIR/servlets/servlet/src/main/webapp"
SMART_DIR="$OUT_DIR/smartphone"
INSTALL_DIR="$OUT_DIR/install"

echo "═══════════════════════════════════════════════════════════════"
echo " NWE Website Generator"
echo " Module:   $MODULE_NAME"
echo " Color:    $MODULE_COLOR"
echo " Database: $MODULE_DB"
echo " Ports:    $PORT_START–$PORT_END"
echo " Pages:    ${#PAGES[@]}"
echo " Nouns:    ${#NOUNS[@]}"
echo " Output:   $OUT_DIR"
echo "═══════════════════════════════════════════════════════════════"
echo ""

mkdir -p "$WEBAPP_DIR/WEB-INF/lib" "$WEBAPP_DIR/css" "$WEBAPP_DIR/js" "$WEBAPP_DIR/images" "$WEBAPP_DIR/sql"
