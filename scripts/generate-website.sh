        case"disconnect":msg="["+ts+"] Disconnecting...\n["+ts+"] Disconnected.\n";break;
        case"status":msg="["+ts+"] STATUS|port="+port+"|OK\n";break;
        default:msg="["+ts+"] "+action+" sent to port "+port+".\n";
    }
    t.value+=msg;t.scrollTop=t.scrollHeight;
}
function cd1Ok(){var t=document.getElementById("cd1-textarea");if(!t)return;t.value+="["+new Date().toLocaleTimeString()+"] OK.\n";t.scrollTop=t.scrollHeight;}
