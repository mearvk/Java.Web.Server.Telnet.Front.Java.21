cat > "$WEBAPP_DIR/sql/create-tables.sql" << SQLHEADER
-- ${MODULE_NAME}™ — Auto-generated schema
-- Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)
CREATE DATABASE IF NOT EXISTS ${MODULE_DB};
USE ${MODULE_DB};

SQLHEADER

for i in "${!NOUNS[@]}"; do
    TABLE="${NOUN_TABLES[$i]}"
    IFS=',' read -ra COLS <<< "${NOUN_COLUMNS[$i]}"
    echo "CREATE TABLE IF NOT EXISTS ${TABLE} (" >> "$WEBAPP_DIR/sql/create-tables.sql"
    for col in "${COLS[@]}"; do
        col=$(echo "$col" | tr -d ' ')
        if [ "$col" = "id" ]; then
            echo "    id BIGINT AUTO_INCREMENT PRIMARY KEY," >> "$WEBAPP_DIR/sql/create-tables.sql"
        elif [[ "$col" == *"_at" ]]; then
            echo "    ${col} DATETIME DEFAULT CURRENT_TIMESTAMP," >> "$WEBAPP_DIR/sql/create-tables.sql"
        elif [[ "$col" == *"active"* ]] || [[ "$col" == *"enabled"* ]]; then
            echo "    ${col} BOOLEAN DEFAULT TRUE," >> "$WEBAPP_DIR/sql/create-tables.sql"
        elif [[ "$col" == *"count"* ]] || [[ "$col" == *"number"* ]] || [[ "$col" == *"year"* ]] || [[ "$col" == *"port"* ]]; then
            echo "    ${col} INT DEFAULT 0," >> "$WEBAPP_DIR/sql/create-tables.sql"
        else
            echo "    ${col} VARCHAR(255)," >> "$WEBAPP_DIR/sql/create-tables.sql"
        fi
    done
    # Remove trailing comma from last column
    sed -i '$ s/,$//' "$WEBAPP_DIR/sql/create-tables.sql"
    echo ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;" >> "$WEBAPP_DIR/sql/create-tables.sql"
    echo "" >> "$WEBAPP_DIR/sql/create-tables.sql"
done

